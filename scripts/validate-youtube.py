def get(url, timeout=25):
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36",
        "Accept-Language": "id-ID,id;q=0.9,en-US;q=0.8",
    })
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "ignore")

def search(query):
    url = "https://www.youtube.com/results?search_query=" + urllib.parse.quote(query)
    html = get(url)
    m = re.search(r"var ytInitialData = (\{.*?\});</script>", html, re.S)
    if not m:
        return []
    data = json.loads(m.group(1))
    out = []
    def walk(node):
        if isinstance(node, dict):
            if "videoRenderer" in node:
                v = node["videoRenderer"]
                vid = v.get("videoId")
                if vid:
                    title = "".join(r.get("text", "") for r in v.get("title", {}).get("runs", []))
                    channel = "".join(r.get("text", "") for r in v.get("ownerText", {}).get("runs", []))
                    out.append((vid, title, channel))
            for val in node.values():
                walk(val)
        elif isinstance(node, list):
            for item in node:
                walk(item)
    walk(data)
    return out

def embeddable(vid):
    try:
        get(f"https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v={vid}&format=json")
        return True
    except Exception:
        return False

results = {}
for title, artist, query in TRACKS:
    try:
        candidates = search(query)
        chosen = None
        tokens = [t for t in re.split(r"[ ,.&]+", artist.lower()) if len(t) > 2]
        for vid, t, ch in candidates[:8]:
            cl = ch.lower()
            if any(tok in cl for tok in tokens):
                chosen = (vid, t, ch)
                break
        if not chosen and candidates:
            chosen = candidates[0]
        if chosen and embeddable(chosen[0]):
            results[title] = {"videoId": chosen[0], "foundTitle": chosen[1], "channel": chosen[2]}
            print(f"OK   {title} | {chosen[0]} | {chosen[1][:55]} | {chosen[2][:45]}")
        else:
            results[title] = None
            print(f"FAIL {title} (tidak embeddable)")
    except Exception as e:
        results[title] = None
        print(f"ERR  {title} | {e}")
    time.sleep(0.4)

lines = ["// Auto-generated by scripts/validate-youtube.py — do not edit manually.",
         "// Verified official, embeddable YouTube video IDs."]
for title, artist, query in TRACKS:
    r = results.get(title)
    vid = json.dumps(r["videoId"]) if r else "null"
    lines.append(f'  {{ title: "{title}", artist: "{artist}", videoId: {vid} }},')
body = "\n".join(lines)
with open("src/data/track-ids.ts", "w") as f:
    f.write("export interface TrackSeed { title: string; artist: string; videoId: string | null }\n\nexport const trackSeeds: TrackSeed[] = [\n" + body + "\n];\n")
print("wrote src/data/track-ids.ts")
